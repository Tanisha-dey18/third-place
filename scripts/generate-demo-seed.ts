// Generates supabase/seed/demo_seed.sql from the bundled demo dataset,
// so the database can hold the same (clearly flagged is_demo = true)
// fictional records with identical IDs. Run: npm run seed:sql
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEMO_CAFES } from '../src/data/demoCafes';

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, '../supabase/seed/demo_seed.sql');

const q = (v: unknown): string => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  return `'${String(v).replace(/'/g, "''")}'`;
};
const arr = (xs: string[]) => (xs.length ? `array[${xs.map(q).join(',')}]::text[]` : `'{}'::text[]`);
const json = (v: unknown) => (v == null ? 'null' : `${q(JSON.stringify(v))}::jsonb`);

const lines: string[] = [
  '-- ════════════════════════════════════════════════════════════════',
  '-- THIRD PLACE · DEMO SEED (generated by scripts/generate-demo-seed.ts)',
  '-- FICTIONAL SAMPLE DATA. Every row is flagged is_demo = true.',
  '-- These are NOT real businesses. Do not load into a production',
  '-- database that presents itself as verified real-world data.',
  '-- Remove later with:  delete from public.cafes where is_demo;',
  '-- ════════════════════════════════════════════════════════════════',
  'begin;',
];

for (const c of DEMO_CAFES) {
  lines.push(
    `insert into public.cafes (id, slug, name, is_demo, tagline, description, neighbourhood, address, latitude, longitude, price_min, price_max, price_status, opening_hours, hours_status, hours_last_verified_at, phone, website, instagram, atmosphere, occasions, noise_level, noise_status, seating_indoor, seating_outdoor, group_friendly, seating_note, food_types, serves_veg, serves_non_veg, dietary_status, tags, accessibility_note, data_source, verification_status, last_verified_at, created_at) values (` +
      [
        q(c.id), q(c.slug), q(c.name), 'true', q(c.tagline), q(c.description), q(c.neighbourhood), q(c.address), q(c.lat), q(c.lng),
        q(c.priceMin), q(c.priceMax), q(c.priceStatus), json(c.hours.value), q(c.hours.status), q(c.hours.lastVerified), q(c.phone), q(c.website), q(c.instagram),
        arr(c.atmosphere), arr(c.occasions), q(c.noise.value), q(c.noise.status), q(c.seating.indoor), q(c.seating.outdoor), q(c.seating.groupFriendly), q(c.seating.note),
        arr(c.foodTypes), q(c.dietary.value?.veg ?? null), q(c.dietary.value?.nonVeg ?? null), q(c.dietary.status), arr(c.tags), q(c.accessibilityNote),
        q(c.dataSource), q(c.verificationStatus), q(c.lastVerified), q(c.createdAt),
      ].join(', ') +
      `) on conflict (id) do update set name = excluded.name, updated_at = now();`,
  );
  for (const f of c.facilities) {
    lines.push(
      `insert into public.cafe_facilities (cafe_id, facility, available, status, note, source, last_verified_at) values (${[q(c.id), q(f.key), q(f.available), q(f.status), q(f.note ?? null), q(f.source ?? null), q(f.lastVerified)].join(', ')}) on conflict (cafe_id, facility) do nothing;`,
    );
  }
  c.photos.forEach((p, i) => {
    lines.push(`insert into public.cafe_photos (cafe_id, url, alt, credit, is_illustrative, sort_order) values (${[q(c.id), q(p.url), q(p.alt), q(p.credit ?? null), q(p.isIllustrative), i].join(', ')});`);
  });
  for (const m of c.menu) {
    lines.push(
      `insert into public.menu_items (id, cafe_id, name, description, category, price_inr, photo_url, dietary, is_bestseller, bestseller_source, is_signature, popularity_note, source, last_updated) values (${[
        q(m.id), q(c.id), q(m.name), q(m.description), q(m.category), q(m.priceInr), q(m.photoUrl), q(m.dietary), q(m.isBestseller), q(m.bestsellerSource), q(m.isSignature), q(m.popularityNote), q(m.source), q(m.lastUpdated),
      ].join(', ')}) on conflict (id) do nothing;`,
    );
  }
}
lines.push('commit;', '');

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lines.join('\n'), 'utf8');
console.log(`Wrote ${DEMO_CAFES.length} demo cafés to ${out}`);
